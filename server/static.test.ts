import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import type { AddressInfo } from 'node:net';
import { createApp } from './app.js';

test('production server serves web assets, HEAD and SPA routes while isolating APIs and unsafe paths', async t => {
  const root = await mkdtemp(join(tmpdir(), 'moneycast-static-test-'));
  await mkdir(join(root, 'assets'));
  await writeFile(join(root, 'index.html'), '<!doctype html><title>MoneyCast fixture</title>');
  await writeFile(join(root, 'assets', 'index-abcdefgh.js'), 'console.log("fixture");');
  await writeFile(join(root, '.env'), 'MUST_NOT_BE_SERVED');
  const app = createApp(undefined, { staticDirectory: root });
  app.listen(0, '127.0.0.1');
  await once(app, 'listening');
  t.after(async () => { app.closeAllConnections(); app.close(); await rm(root, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${(app.address() as AddressInfo).port}`;
  const home = await fetch(base);
  assert.equal(home.status, 200);
  assert.match(home.headers.get('content-type')!, /text\/html/);
  assert.match(await home.text(), /MoneyCast fixture/);
  const asset = await fetch(`${base}/assets/index-abcdefgh.js`);
  assert.equal(asset.status, 200);
  assert.match(asset.headers.get('content-type')!, /text\/javascript/);
  assert.match(asset.headers.get('cache-control')!, /immutable/);
  assert.match(await asset.text(), /fixture/);
  const head = await fetch(base, { method: 'HEAD' });
  assert.equal(head.status, 200);
  assert.equal(await head.text(), '');
  assert.ok(Number(head.headers.get('content-length')) > 0);
  assert.match(await (await fetch(`${base}/calculator`)).text(), /MoneyCast fixture/);
  assert.equal((await fetch(`${base}/assets/missing.js`)).status, 404);
  assert.equal((await fetch(`${base}/api/unknown`)).status, 404);
  assert.equal((await fetch(`${base}/.env`)).status, 404);
  assert.equal((await fetch(`${base}/..%5Cprivate.txt`)).status, 400);
  assert.equal((await fetch(`${base}/%00`)).status, 400);
  assert.equal((await fetch(`${base}/%E0`)).status, 400);
  assert.equal((await fetch(base, { method: 'POST' })).status, 405);
});
